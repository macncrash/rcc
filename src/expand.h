/*
 * expand.h - macro expansion: cfg stripping, `mod foo;` loading,
 * macro_rules!, builtin macros, #[derive].
 *
 * expand_crate() parses the crate root, loads every out-of-line module and
 * expands the whole crate to a fixpoint. The result contains
 *   - no macro invocations (EXPR_MAC, STMT_MAC, ITEM_MAC, PAT_MAC, TY_MAC),
 *   - no ITEM_MACRO_RULES items,
 *   - no #[cfg] / #[cfg_attr] / #[derive] / #[test] / #[path] / #[macro_use]
 *     / #[macro_export] attributes (and nothing cfg'd out),
 *   - every `mod foo;` replaced by an inline module (mod.inline_ == true)
 *     holding the loaded file's items; the file's inner attributes are
 *     appended to the module item's attrs with Attr.inner == true. Spans of
 *     nodes from that file keep pointing into it.
 * Every node has a unique NodeId. Nodes generated by builtin macros and
 * derives carry the span of the macro call (or of the derived item).
 *
 * Builtin macros are lowered exactly as described in DESIGN.md
 * ("Contract between the expander and std"); see docs/STATUS.md
 * ("Expander") for the precise shapes and the reserved `__rcc_` names.
 */
#ifndef RCC_EXPAND_H
#define RCC_EXPAND_H

#include "ast.h"

typedef struct ExpandOptions {
    /* --cfg specs: `name` or `key="value"`. A `target_*` key replaces the
       host value for that key instead of adding a second value. */
    const char **cfgs;
    uint32_t ncfgs;
    /* --env K=V overrides for env!/option_env! (else the process env). */
    const char **envs;
    uint32_t nenvs;
    /* Compat mode (for checking the expander against real rustc): the
       format family, panic family, assert family and thread_local! are left
       as macro calls whose arguments are expanded. Everything else is
       expanded as usual. */
    bool compat;
    /* Path prefix for the std items of the formatting contract (Arguments,
       Piece, Argument, Spec, Align, format, _print, _eprint, panic_fmt,
       assert_failed). NULL means "::std". The test mock uses
       "crate::std_mock"; then write!/writeln! lower to
       `d.write_fmt(::std::format_args!("{}", ARGS))`. */
    const char *fmt_root;
} ExpandOptions;

/*
 * Parse and expand the crate whose root file is `root_path`. `crate_name`
 * is used for module_path!(). Fatal on any error.
 */
Crate *expand_crate(const char *root_path, const char *crate_name,
                    const ExpandOptions *opts);

/* AST -> Rust source pretty-printer (astprint.c). The output is valid,
   re-parseable Rust for expanded crates. */
void ast_print_crate(FILE *out, const Crate *c);
/* Render to arena strings (used by stringify! and assert! messages). */
const char *ast_expr_to_str(const Expr *e);
const char *ast_ty_to_str(const Ty *t);
const char *ast_pat_to_str(const Pat *p);
const char *ast_path_to_str(const Path *p);
const char *ast_tokens_to_str(TokenList tl);

#endif
