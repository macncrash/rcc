extern "C" {
    fn rcc_thr_spawn(
        stack: usize,
        body: fn(*mut u8) -> i32,
        on_panic: fn(*mut u8) -> i32,
        arg: *mut u8,
        err: *mut i32,
    ) -> *mut u8;
    fn rcc_thr_join(h: *mut u8) -> i32;
    fn rcc_thr_detach(h: *mut u8);
    fn rcc_thr_is_main() -> i32;
    fn rcc_thr_unwind() -> !;
    fn rcc_thr_set_c_panic_hook(f: fn(*const u8, usize, i32) -> i32);
    fn rcc_thr_yield();
    fn rcc_thr_sleep(secs: u64, nanos: u32);
    // rcc_thr_ncpu() -> usize exists for `available_parallelism` (needs NonZeroUsize)
}

/// Result of joining a thread: `Err` holds the panic payload.
pub type Result<T> = crate::result::Result<T, Box<dyn Any + Send + 'static>>;

/// Stack size of threads spawned without `Builder::stack_size` (real std
/// uses 2 MiB; C frames generated by rcc are larger than rustc's).
const DEFAULT_STACK: usize = 8 << 20;

// ---------------------------------------------------------------------------
// Thread handles and ids
// ---------------------------------------------------------------------------

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
pub struct ThreadId(u64);

/// 1 is the main thread.
static NEXT_THREAD_ID: AtomicU64 = AtomicU64::new(2);

impl ThreadId {
    fn fresh() -> ThreadId {
        ThreadId(NEXT_THREAD_ID.fetch_add(1, Ordering::Relaxed))
    }
    pub fn as_u64(&self) -> u64 {
        self.0
    }
}

struct ThreadInner {
    name: Option<String>,
    id: ThreadId,
}

#[derive(Clone)]
pub struct Thread {
    inner: Arc<ThreadInner>,
}

impl Thread {
    fn new(name: Option<String>, id: ThreadId) -> Thread {
        Thread { inner: Arc::new(ThreadInner { name, id }) }
    }
    pub fn id(&self) -> ThreadId {
        self.inner.id
    }
    pub fn name(&self) -> Option<&str> {
        match &self.inner.name {
            Some(s) => Some(s.as_str()),
            None => None,
        }
    }
    /// Parking is not implemented beyond yielding (`park` may return
    /// spuriously, as real std allows).
    pub fn unpark(&self) {}
}

impl fmt::Debug for Thread {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Thread").field("id", &self.id()).field("name", &self.name()).finish_non_exhaustive()
    }
}

fn no_thread() -> RefCell<Option<Thread>> {
    RefCell::new(None)
}

/// The calling thread's handle (set by `thread_main`; created lazily on the
/// main thread).
static CURRENT: LocalKey<RefCell<Option<Thread>>> = LocalKey::new(no_thread);

pub fn current() -> Thread {
    CURRENT.with(|c| {
        if c.borrow().is_none() {
            let t = if on_main_thread() {
                Thread::new(Some(String::from("main")), ThreadId(1))
            } else {
                Thread::new(None, ThreadId::fresh())
            };
            *c.borrow_mut() = Some(t);
        }
        c.borrow().as_ref().unwrap().clone()
    })
}

pub(crate) fn on_main_thread() -> bool {
    unsafe { rcc_thr_is_main() != 0 }
}

pub fn yield_now() {
    unsafe { rcc_thr_yield() }
}

pub fn sleep(dur: crate::time::Duration) {
    unsafe { rcc_thr_sleep(dur.as_secs(), dur.subsec_nanos()) }
}

pub fn sleep_ms(ms: u32) {
    unsafe { rcc_thr_sleep((ms / 1000) as u64, (ms % 1000) * 1_000_000) }
}

/// Without unwinding no code runs while a thread is panicking.
pub fn panicking() -> bool {
    false
}

pub fn park() {
    yield_now()
}

// ---------------------------------------------------------------------------
// Panic capture (used by crate::panic)
// ---------------------------------------------------------------------------

fn no_payload() -> RefCell<Option<Box<dyn Any + Send>>> {
    RefCell::new(None)
}

static PANIC_PAYLOAD: LocalKey<RefCell<Option<Box<dyn Any + Send>>>> = LocalKey::new(no_payload);

/// Name used in the "thread '..' panicked" message.
pub(crate) fn panic_thread_name(f: &mut dyn FnMut(&str)) {
    if on_main_thread() {
        f("main");
        return;
    }
    let t = current();
    match t.name() {
        Some(n) => f(n),
        None => f("<unnamed>"),
    }
}

/// Leave the current spawned thread with `payload` (see the module doc).
pub(crate) fn unwind_with(payload: Box<dyn Any + Send>) -> ! {
    PANIC_PAYLOAD.with(|slot| *slot.borrow_mut() = Some(payload));
    unsafe { rcc_thr_unwind() }
}

fn install_c_panic_hook() {
    unsafe { rcc_thr_set_c_panic_hook(crate::panic::c_panic_hook) }
}

// ---------------------------------------------------------------------------
// Spawning
// ---------------------------------------------------------------------------

/// The result slot shared by the thread and its join handle.
struct Packet<T> {
    scope: Option<Arc<ScopeData>>,
    result: UnsafeCell<Option<Result<T>>>,
}

unsafe impl<T: Send> Sync for Packet<T> {}

impl<T> Drop for Packet<T> {
    fn drop(&mut self) {
        let unhandled_panic = match unsafe { &*self.result.get() } {
            Some(Err(_)) => true,
            _ => false,
        };
        unsafe { *self.result.get() = None };
        if let Some(scope) = &self.scope {
            scope.decrement_num_running_threads(unhandled_panic);
        }
    }
}

/// Everything the new thread owns; freed by `thread_main` or `thread_panicked`.
struct Start<F, T> {
    /// taken by `thread_main` (ManuallyDrop, not Option: see
    /// tests/core/pending/option_of_closure_is_copy.rs); leaked if spawning fails
    f: ManuallyDrop<F>,
    packet: Arc<Packet<T>>,
    thread: Thread,
}

fn thread_main<F: FnOnce() -> T, T>(arg: *mut u8) -> i32 {
    unsafe {
        let start = arg as *mut Start<F, T>;
        let me = (*start).thread.clone();
        CURRENT.with(|c| *c.borrow_mut() = Some(me));
        let f = ManuallyDrop::take(&mut (*start).f);
        let v = f();
        *(*start).packet.result.get() = Some(Ok(v));
        drop(Box::from_raw(start));
    }
    0
}

fn thread_panicked<F: FnOnce() -> T, T>(arg: *mut u8) -> i32 {
    unsafe {
        let start = arg as *mut Start<F, T>;
        let payload = match PANIC_PAYLOAD.with(|slot| slot.borrow_mut().take()) {
            Some(p) => p,
            None => Box::new("explicit panic") as Box<dyn Any + Send>,
        };
        *(*start).packet.result.get() = Some(Err(payload));
        drop(Box::from_raw(start));
    }
    0
}

struct JoinInner<T> {
    native: *mut u8,
    thread: Thread,
    packet: Arc<Packet<T>>,
}

impl<T> JoinInner<T> {
    fn join(mut self) -> Result<T> {
        unsafe { rcc_thr_join(self.native) };
        self.native = 0usize as *mut u8;
        match unsafe { (*self.packet.result.get()).take() } {
            Some(r) => r,
            None => panic!("thread result missing"),
        }
    }
    fn is_finished(&self) -> bool {
        Arc::strong_count(&self.packet) == 1
    }
}

impl<T> Drop for JoinInner<T> {
    fn drop(&mut self) {
        if !self.native.is_null() {
            unsafe { rcc_thr_detach(self.native) };
        }
    }
}

fn spawn_inner<F, T>(
    name: Option<String>,
    stack_size: Option<usize>,
    f: F,
    scope: Option<Arc<ScopeData>>,
) -> io::Result<JoinInner<T>>
where
    F: FnOnce() -> T,
{
    install_c_panic_hook();
    let thread = Thread::new(name, ThreadId::fresh());
    if let Some(s) = &scope {
        s.increment_num_running_threads();
    }
    let packet: Arc<Packet<T>> = Arc::new(Packet { scope, result: UnsafeCell::new(None) });
    let start = Box::into_raw(Box::new(Start { f: ManuallyDrop::new(f), packet: packet.clone(), thread: thread.clone() }));
    let stack = match stack_size {
        Some(n) => n,
        None => DEFAULT_STACK,
    };
    let mut err = 0i32;
    let native = unsafe { rcc_thr_spawn(stack, thread_main::<F, T>, thread_panicked::<F, T>, start as *mut u8, &mut err) };
    if native.is_null() {
        unsafe { drop(Box::from_raw(start)) };
        return Err(io::Error::from_raw_os_error(err));
    }
    Ok(JoinInner { native, thread, packet })
}

pub struct JoinHandle<T> {
    inner: JoinInner<T>,
}

unsafe impl<T> Send for JoinHandle<T> {}
unsafe impl<T> Sync for JoinHandle<T> {}

impl<T> JoinHandle<T> {
    pub fn join(self) -> Result<T> {
        let JoinHandle { inner } = self;
        inner.join()
    }
    pub fn thread(&self) -> &Thread {
        &self.inner.thread
    }
    pub fn is_finished(&self) -> bool {
        self.inner.is_finished()
    }
}

impl<T> fmt::Debug for JoinHandle<T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("JoinHandle { .. }")
    }
}

#[derive(Debug)]
pub struct Builder {
    name: Option<String>,
    stack_size: Option<usize>,
}

impl Builder {
    pub fn new() -> Builder {
        Builder { name: None, stack_size: None }
    }
    pub fn name(self, name: String) -> Builder {
        Builder { name: Some(name), stack_size: self.stack_size }
    }
    pub fn stack_size(self, size: usize) -> Builder {
        Builder { name: self.name, stack_size: Some(size) }
    }
    pub fn spawn<F, T>(self, f: F) -> io::Result<JoinHandle<T>>
    where
        F: FnOnce() -> T,
    {
        let Builder { name, stack_size } = self;
        match spawn_inner(name, stack_size, f, None) {
            Ok(inner) => Ok(JoinHandle { inner }),
            Err(e) => Err(e),
        }
    }
    pub fn spawn_scoped<'scope, 'env, F, T>(
        self,
        scope: &'scope Scope<'scope, 'env>,
        f: F,
    ) -> io::Result<ScopedJoinHandle<'scope, T>>
    where
        F: FnOnce() -> T,
    {
        let Builder { name, stack_size } = self;
        match spawn_inner(name, stack_size, f, Some(scope.data.clone())) {
            Ok(inner) => Ok(ScopedJoinHandle { inner, _scope: PhantomData }),
            Err(e) => Err(e),
        }
    }
}

pub fn spawn<F, T>(f: F) -> JoinHandle<T>
where
    F: FnOnce() -> T,
{
    Builder::new().spawn(f).expect("failed to spawn thread")
}

// ---------------------------------------------------------------------------
// Scoped threads
// ---------------------------------------------------------------------------

struct ScopeData {
    num_running_threads: AtomicUsize,
    a_thread_panicked: AtomicBool,
}

impl ScopeData {
    fn increment_num_running_threads(&self) {
        self.num_running_threads.fetch_add(1, Ordering::Relaxed);
    }
    fn decrement_num_running_threads(&self, panic: bool) {
        if panic {
            self.a_thread_panicked.store(true, Ordering::Relaxed);
        }
        self.num_running_threads.fetch_sub(1, Ordering::Release);
    }
}

pub struct Scope<'scope, 'env: 'scope> {
    data: Arc<ScopeData>,
    _marker: PhantomData<&'scope mut &'env ()>,
}

pub struct ScopedJoinHandle<'scope, T> {
    inner: JoinInner<T>,
    _scope: PhantomData<&'scope ()>,
}

/// Run `f` with a scope whose threads may borrow from the caller; all of
/// them are finished when `scope` returns. Panics if one of them panicked
/// and was not joined.
pub fn scope<'env, F, T>(f: F) -> T
where
    F: for<'scope> FnOnce(&'scope Scope<'scope, 'env>) -> T,
{
    let s = Scope {
        data: Arc::new(ScopeData { num_running_threads: AtomicUsize::new(0), a_thread_panicked: AtomicBool::new(false) }),
        _marker: PhantomData,
    };
    let result = f(&s);
    let mut spins = 0u32;
    while s.data.num_running_threads.load(Ordering::Acquire) != 0 {
        crate::sync::backoff(&mut spins);
    }
    if s.data.a_thread_panicked.load(Ordering::Relaxed) {
        panic!("a scoped thread panicked");
    }
    result
}

impl<'scope, 'env> Scope<'scope, 'env> {
    pub fn spawn<F, T>(&'scope self, f: F) -> ScopedJoinHandle<'scope, T>
    where
        F: FnOnce() -> T,
    {
        Builder::new().spawn_scoped(self, f).expect("failed to spawn thread")
    }
}

impl<'scope, 'env> fmt::Debug for Scope<'scope, 'env> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("Scope { .. }")
    }
}

impl<'scope, T> ScopedJoinHandle<'scope, T> {
    pub fn join(self) -> Result<T> {
        let ScopedJoinHandle { inner, _scope } = self;
        inner.join()
    }
    pub fn thread(&self) -> &Thread {
        &self.inner.thread
    }
    pub fn is_finished(&self) -> bool {
        self.inner.is_finished()
    }
}
