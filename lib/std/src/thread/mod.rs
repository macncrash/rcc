//! Threads: real OS threads (pthreads, through the `rcc_thr_*` block of
//! rt/rt.c), with the requested stack size.
//!
//! Spawning: the closure, the shared result `Packet` and the `Thread`
//! handle go to the new thread in one heap allocation (`Start`). rt.c runs
//! `thread_main::<F, T>(start)` on the new thread after a `setjmp`.
//!
//! Panics never unwind (DESIGN.md). A panic on a spawned thread prints the
//! message, stores the payload (`&'static str` for a literal-only message,
//! `String` otherwise, as real std) in this thread's `PANIC_PAYLOAD` slot and
//! calls `rcc_thr_unwind`, which `longjmp`s back to the thread's entry in
//! rt.c. No destructor of the abandoned frames runs (their resources leak,
//! a `MutexGuard` held there keeps its mutex locked). rt.c then calls
//! `thread_panicked::<F, T>(start)`, which stores `Err(payload)` in the
//! packet for `join`. A panic on the main thread prints and exits with 101.

