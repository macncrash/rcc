#!/usr/bin/env python3
"""Generate std_mock.rs: the expander/std formatting contract (DESIGN.md)
implemented as an ordinary crate on top of the real std, so that code
expanded with `rcc --expand --fmt-root ::std_mock` can be compiled by rustc
and its output compared with the original program.

Usage: gen_std_mock.py OUT.rs

Dynamic fill characters cannot be passed to std's formatter, so every
(fill, align, sign, #, 0, precision?) combination for every trait is
spelled out as a literal format string. Fills outside FILLS make the mock
panic, so tests must only use these.
"""
import sys

FILLS = [' ', '*', '-', '_', '0', '#', '.', '─', 'x']
ALIGNS = [('Unknown', ''), ('Left', '<'), ('Center', '^'), ('Right', '>')]
TRAITS = [  # (variant, std trait, type suffix)
    ('Display', 'Display', ''),
    ('Debug', 'Debug', '?'),
    ('LowerHex', 'LowerHex', 'x'),
    ('UpperHex', 'UpperHex', 'X'),
    ('Octal', 'Octal', 'o'),
    ('Binary', 'Binary', 'b'),
    ('LowerExp', 'LowerExp', 'e'),
    ('UpperExp', 'UpperExp', 'E'),
    ('Pointer', 'Pointer', 'p'),
    ('DebugLowerHex', 'Debug', 'x?'),
    ('DebugUpperHex', 'Debug', 'X?'),
]


def rs_char(c):
    if c == "'":
        return "'\\''"
    return "'" + c + "'"


def fmt_fn(variant, trait, ty):
    out = []
    out.append(f"fn spec_{variant}(f: &mut sf::Formatter<'_>, v: &dyn sf::{trait}, s: &Spec) -> sf::Result {{")
    out.append("    let w = s.width.unwrap_or(0);")
    out.append("    let p = s.precision.unwrap_or(0);")
    out.append("    let hp = s.precision.is_some();")
    out.append("    match (s.fill, &s.align, s.sign_plus, s.sign_minus, s.alternate, s.zero_pad, hp) {")
    for aname, ach in ALIGNS:
        fills = [' '] if aname == 'Unknown' else FILLS
        for fill in fills:
            for sign in ('', '+', '-'):
                plus = sign == '+'
                minus = sign == '-'
                for alt in (False, True):
                    for zero in (False, True):
                        for prec in (False, True):
                            spec = ''
                            if ach:
                                spec += ('' if fill == ' ' and False else fill) + ach
                            spec += sign
                            if alt:
                                spec += '#'
                            if zero:
                                spec += '0'
                            spec += 'w$'
                            if prec:
                                spec += '.p$'
                            spec += ty
                            fs = '{:' + spec + '}'
                            fs = fs.replace('{', '{{', 0)
                            pat = f"({rs_char(fill)}, Align::{aname}, {str(plus).lower()}, {str(minus).lower()}, {str(alt).lower()}, {str(zero).lower()}, {str(prec).lower()})"
                            lit = fs.replace('\\', '\\\\').replace('"', '\\"')
                            if fill == '{' or fill == '}':
                                continue
                            args = 'v, w = w' + (', p = p' if prec else '')
                            out.append(f'        {pat} => write!(f, "{lit}", {args}),')
    out.append('        (c, _, _, _, _, _, _) => panic!("std_mock: unsupported fill {:?}", c),')
    out.append("    }")
    out.append("}")
    return "\n".join(out)


