fn main() {
    let mut s = String::new();
    println!("[{}] len {} empty {}", s, s.len(), s.is_empty());
    s.push_str("hello");
    s.push(',');
    s.push(' ');
    s.push_str("world");
    println!("[{}] len {}", s, s.len());
    let t = s.clone() + "!" + &String::from("?");
    println!("{}", t);
    let mut u = String::from("abc");
    u += "def";
    u += &t[0..2];
    println!("{}", u);
    println!("as_str {}", u.as_str());
    let r: &str = &u;
    println!("deref {}", r.len());
    u.insert(0, '>');
    u.insert_str(1, "> ");
    println!("{}", u);
    println!("pop {:?} -> {}", u.pop(), u);
    println!("remove {} -> {}", u.remove(0), u);
    u.truncate(4);
    println!("truncate {}", u);
    u.clear();
    println!("cleared [{}] {}", u, u.is_empty());
    let w = String::with_capacity(10);
    println!("cap {}", w.capacity() >= 10);
    let x = "literal".to_string();
    let y = String::from("literal");
    let z: String = "literal".into();
    let q = "literal".to_owned();
    println!("{} {} {}", x == y, y == z, z == q);
    println!("cmp {} {} {}", "abc" < "abd", "b" > "abc", String::from("x") == "x");
    let rep = "ab".repeat(4);
    println!("{}", rep);
    let mut st = String::from("keep this part only");
    st.retain(|c| c != ' ');
    println!("{}", st);
    let ch: String = std::iter::repeat('z').take(3).collect();
    println!("{}", ch);
}
