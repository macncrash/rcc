fn main() {
    let mut v = vec![10, 20, 30, 40, 50];
    v.insert(0, 5);
    println!("{:?}", v);
    v.insert(3, 25);
    println!("{:?}", v);
    let n = v.len();
    v.insert(n, 99);
    println!("{:?}", v);
    let r = v.remove(1);
    println!("removed {} -> {:?}", r, v);
    let r = v.remove(v.len() - 1);
    println!("removed {} -> {:?}", r, v);
    let s = v.swap_remove(0);
    println!("swap_removed {} -> {:?}", s, v);
    v.swap(0, 2);
    println!("swapped {:?}", v);
    v.truncate(3);
    println!("truncated {:?}", v);
    v.truncate(10);
    println!("truncate bigger {:?}", v);
    v.resize(6, -1);
    println!("resized {:?}", v);
    v.resize(2, 0);
    println!("resized down {:?}", v);
    let mut names: Vec<String> = vec!["b".into(), "d".into()];
    names.insert(0, "a".into());
    names.insert(2, "c".into());
    println!("{:?}", names);
    let x = names.remove(2);
    println!("{} {:?}", x, names);
    let mut sp = vec![1, 2, 3, 4, 5, 6];
    let tail = sp.split_off(4);
    println!("split_off {:?} {:?}", sp, tail);
    let mut a = vec![1, 2];
    let mut b = vec![3, 4, 5];
    a.append(&mut b);
    println!("append {:?} {:?}", a, b);
}
