fn main() {
    println!("{:+} {:+} {:+}", 5, -5, 0);
    println!("{:+.2} {:+.2} {:+}", 1.5, -1.5, 0.0);
    println!("{:+} {:+}", -0.0f64, f64::INFINITY);
    println!("[{:05}] [{:05}] [{:05}]", 42, -42, 123456);
    println!("[{:+05}] [{:+06}]", 42, -42);
    println!("[{:08.3}] [{:08.3}] [{:+09.2}]", 3.14159, -3.14159, 2.5);
    println!("[{:<05}] [{:^05}] [{:>05}]", 7, 7, 7);
    println!("[{:#06x}] [{:#06b}] [{:06x}]", 0xab, 3, -1i8);
    println!("[{:05}] [{:05}]", f64::NAN, f64::NEG_INFINITY);
    println!("[{:010}]", i64::MIN);
    println!("[{:03}]", 1000);
    println!("[{:01}]", 0);
    println!("[{:+}]", u64::MAX);
    println!("[{:+e}] [{:+E}]", 1500.0, -0.00025);
    let w = 7;
    println!("[{:0w$}] [{:+0w$.1}]", -3, 9.99, w = w);
    println!("[{:0>5}] [{:0<5}]", "ab", "ab");
}
